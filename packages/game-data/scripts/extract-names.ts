/**
 * Generates src/generated/names.json: the game's display names for buildings and creatures
 * (what worldgen places in a world) and for the base-game space destinations.
 *
 * - prefab names come from `STRINGS.BUILDINGS.PREFABS.<ID>.NAME` and
 *   `STRINGS.CREATURES.SPECIES.<ID>.NAME` in strings_template.pot, keyed by the ID with
 *   underscores removed (the game writes `OIL_WELL` for the prefab `OilWell`).
 * - destination names come from the decompiled `SpaceDestinationTypes`, which names each type
 *   id (`HeliumGiant`) after a string key (`UI.SPACEDESTINATIONS.GIANTS.HYDROGENGIANT.NAME`).
 *
 * Usage: vp run extract-names   (ONI_PATH for the game, ONI_DECOMP for the decompile)
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { clean } from './extract/collect.ts'
import { dataDir, decompDir } from './extract/paths.ts'
import { readPot } from './extract/pot.ts'

const strings = readPot(join(dataDir(), 'StreamingAssets/strings/strings_template.pot'))

const prefabs: Record<string, string> = {}
const PREFAB_KEY = /^STRINGS\.(?:BUILDINGS\.PREFABS|CREATURES\.SPECIES)\.([A-Z0-9_]+)\.NAME$/
for (const [key, name] of strings) {
  const id = PREFAB_KEY.exec(key)?.[1]?.replaceAll('_', '')
  if (id && !(id in prefabs)) prefabs[id] = clean(name)
}

const destinations: Record<string, string> = {}
const source = readFileSync(
  join(decompDir(), 'Assembly-CSharp/Database/SpaceDestinationTypes.cs'),
  'utf8',
)
const DESTINATION =
  /new SpaceDestinationType\("(\w+)",\s*parent,\s*UI\.SPACEDESTINATIONS\.([A-Z0-9_.]+)\.NAME/g
for (const [, id, path] of source.matchAll(DESTINATION)) {
  const name = strings.get(`STRINGS.UI.SPACEDESTINATIONS.${path}.NAME`)
  if (id && name) destinations[id] = clean(name)
}

const data = {
  source:
    "Generated by packages/game-data/scripts/extract-names.ts from the game's strings and SpaceDestinationTypes.",
  prefabs: Object.fromEntries(Object.entries(prefabs).sort(([a], [b]) => a.localeCompare(b))),
  destinations,
}
writeFileSync(
  new URL('../src/generated/names.json', import.meta.url),
  `${JSON.stringify(data, null, 1)}\n`,
)
console.log(
  `prefabs: ${Object.keys(prefabs).length}, destinations: ${Object.keys(destinations).length}`,
)
